// Token radar, model "radar-2": a comparables model derived from the snapshot itself.
//
// Every implied value is built from the snapshot's own figures, never from a
// hand-written list of names. For each category, the model takes the MEDIAN
// mcap/TVL ratio of the live-token protocols in that category (protocols that
// already trade, so the market has priced them), and applies that multiple to
// a pre-token protocol's TVL. Categories with fewer than 3 live peers fall
// back to the global median, so no thin category gets an extreme multiple.
// The multiple is clamped to [0.05, 1.50].
//
//   multiple   = clamp(median(mcap_usd / tvl_usd over live peers), 0.05, 1.50)
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d ?? 0, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.35
//   maturity   = 0.7 + min(age_days, 1460) / 1460 x 0.5   (age unknown: 365)
//   breadth    = 1 + 0.03 x min(chains, 5)
//   implied    = max(1, round(base x growthMult x maturityMult x breadthMult))
//
// The board ranks every rankable protocol: all 40 watchlist slugs, plus the
// early rankable protocols below the floor, ordered by implied value. This
// snapshot holds 143 rankable protocols below the floor (163 rankable outside
// the watchlist in all), so the board is 183 rows: all 40 watchlist slugs
// plus the 143 rankable protocols below the floor. The 20 rankable
// protocols above the floor stay out: they sit above the snapshot's own
// cut-off, so they are not early finds. The code still asks for up to 260
// early rows, so the count is the data's, not a hard-coded board size.
//
// A protocol is rankable when it records no token (mcap, gecko_id and symbol
// all null), its category is not one of the wrapped / staked / bridged /
// exchange buckets, its name does not end in a version marker, and it does
// not begin with an exchange's name. Live-token protocols are never ranked:
// they are shown apart, at the market's own value.

